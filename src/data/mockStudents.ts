import { Student, calculateGrade, calculateCgpa, DEFAULT_SUBJECTS } from '../types/studentApp';

function makeMockStudent(
  id: string,
  rollNo: string,
  name: string,
  email: string,
  phone: string,
  department: string,
  semester: string,
  academicYear: string,
  dateOfBirth: string,
  gender: 'Male' | 'Female' | 'Other',
  status: 'Active' | 'On Leave' | 'Suspended' | 'Graduated',
  guardianName: string,
  guardianPhone: string,
  city: string,
  markValues: [number, number, number, number, number],
  attended: number,
  totalClasses: number,
  totalFee: number,
  paidFee: number,
  dueDate: string,
  enrolledDate: string
): Student {
  const subjects = DEFAULT_SUBJECTS.map((sub, i) => {
    const marks = markValues[i];
    const { grade, gradePoint } = calculateGrade(marks);
    return {
      ...sub,
      marks,
      grade,
      gradePoint,
    };
  });

  const cgpa = calculateCgpa(subjects);
  const attendancePct = Math.round((attended / totalClasses) * 100);
  const attendanceStatus =
    attendancePct >= 75 ? 'Good' : attendancePct >= 65 ? 'Warning' : 'Critical';

  const dueFee = totalFee - paidFee;
  const feeStatus = dueFee <= 0 ? 'Paid' : paidFee > 0 ? 'Partial' : 'Overdue';

  return {
    id,
    rollNo,
    name,
    email,
    phone,
    department,
    semester,
    academicYear,
    dateOfBirth,
    gender,
    status,
    avatarSeed: name.toLowerCase().replace(/\s+/g, '-'),
    guardianName,
    guardianPhone,
    address: `Plot ${Math.floor(Math.random() * 80) + 12}, Tech Enclave, Sector 4`,
    city,
    cgpa,
    subjects,
    attendance: {
      totalClasses,
      attendedClasses: attended,
      percentage: attendancePct,
      status: attendanceStatus,
    },
    fee: {
      totalFee,
      paidFee,
      dueFee,
      status: feeStatus,
      dueDate,
    },
    enrolledDate,
  };
}

